"""Schema parity gate: Alembic migrations must produce EXACTLY the schema that
schema.sql declares, since schema.sql is the source of truth.

CI (using .github/actions/ci-db):
  PARITY_DB_REFERENCE = scratch DB with schema.sql applied
  PARITY_DB_LIVE      = scratch DB migrated by `alembic upgrade head`
This test fails the branch when table, column or index definitions drift in
either direction (a hand-edited schema.sql, or an autogenerated migration).

Locally without those env vars it skips.
"""

import os

import pytest
from sqlalchemy import create_engine, text


def _snapshot(url: str) -> dict:
    engine = create_engine(url, pool_pre_ping=True)
    try:
        with engine.connect() as conn:
            tables = sorted(
                r[0]
                for r in conn.execute(
                    text("""
                        SELECT table_name FROM information_schema.tables
                        WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
                    """)
                )
                # alembic_version is migration bookkeeping, not declared schema
                if r[0] != "alembic_version"
            )
            columns: dict[str, dict[str, tuple]] = {}
            for r in conn.execute(
                text("""
                    SELECT table_name, column_name, udt_name, is_nullable,
                           column_default, numeric_precision, numeric_scale,
                           character_maximum_length
                    FROM information_schema.columns
                    WHERE table_schema = 'public' AND table_name != 'alembic_version'
                    ORDER BY table_name, ordinal_position
                """)
            ):
                m = r._mapping
                columns.setdefault(m["table_name"], {})[m["column_name"]] = (
                    m["udt_name"],
                    m["is_nullable"],
                    _norm_default(m["column_default"]),
                    m["numeric_precision"],
                    m["numeric_scale"],
                    m["character_maximum_length"],
                )
            indexes: dict[str, list[str]] = {}
            for r in conn.execute(
                text("""
                    SELECT tablename, indexname FROM pg_indexes
                    WHERE schemaname = 'public' AND indexname NOT LIKE '%_pkey'
                    ORDER BY tablename, indexname
                """)
            ):
                indexes.setdefault(r[0], []).append(r[1])
            return {"tables": tables, "columns": columns, "indexes": indexes}
    finally:
        engine.dispose()


def _norm_default(default: str | None) -> str | None:
    return None if default is None else " ".join(default.split()).lower()


def test_alembic_head_matches_schema_sql() -> None:
    ref_url = os.environ.get("PARITY_DB_REFERENCE")
    live_url = os.environ.get("PARITY_DB_LIVE")
    if not (ref_url and live_url):
        pytest.skip("PARITY_DB_* not set — needs the CI Postgres (.github/actions/ci-db)")

    reference = _snapshot(ref_url)
    migrated = _snapshot(live_url)

    assert migrated["tables"] == reference["tables"], (
        "tables drifted:\n"
        f"only in schema.sql: {set(reference['tables']) - set(migrated['tables'])}\n"
        f"only in migrations: {set(migrated['tables']) - set(reference['tables'])}"
    )
    assert migrated["columns"] == reference["columns"], (
        "columns drifted (type/nullable/default/precision):\n"
        f"migrations version: {migrated['columns']}\n"
        f"schema.sql version: {reference['columns']}"
    )
    assert migrated["indexes"] == reference["indexes"], (
        "indexes drifted:\n"
        f"schema.sql indexes: {reference['indexes']}\n"
        f"migration indexes: {migrated['indexes']}"
    )
